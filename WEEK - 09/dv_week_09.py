df['date'] = pd.to_datetime(
    df['date'],
    format='%Y%m%dT%H%M%S'
)

df['date'].head()

df["sale_year"] = df["date"].dt.year
df["sale_month"] = df["date"].dt.month
df["sale_day"] = df["date"].dt.day
df["sale_hour"] = df["date"].dt.hour
df["sale_minute"] = df["date"].dt.minute
df["sale_second"] = df["date"].dt.second

df.head()

df.dropna(subset=["price", "sqft_living", "sqft_lot"], inplace=True)
df = df[(df["price"] > 0) & (df["sqft_living"] > 0)
        & (df["sqft_lot"] > 0)]

df["sale_year"] = df["date"].dt.year
df["sale_month"] = df["date"].dt.month
df["property_age"] = df["sale_year"] - df["yr_built"]
df["is_renovated"] = (df["yr_renovated"] > 0).astype(int)

df["years_since_renovation"] = np.where(
    df["yr_renovated"] > 0,
    df["sale_year"] - df["yr_renovated"], 0
)

df["price_per_sqft_living"] = df["price"] / df["sqft_living"]
df["price_per_sqft_lot"] = df["price"] / df["sqft_lot"]

Q1 = df["price"].quantile(0.25)
Q3 = df["price"].quantile(0.75)
IQR = Q3 - Q1

outliers = df[(df["price"] < Q1 - 1.5 * IQR) |
              (df["price"] > Q3 + 1.5 * IQR)]

print("Price Outliers:", len(outliers))

df.to_csv("House_Sales_Data_Cleaned_Week_09.csv", index=False)